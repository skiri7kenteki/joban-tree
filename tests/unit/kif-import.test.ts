// 段階8-2：変化付き KIF から研究手順をまとめて取り込む
import { describe, expect, it } from 'vitest';
import { KIF_IMPORT_MAX, NOTE_MAX, buildCandidates, candidatesToStudies, cleanComment, decodeKifFile, kifSide, readKif } from '../../src/tree/kifImport';
import { studiesToKif } from '../../src/tree/studyFile';
import type { OpeningTemplate } from '../../src/tree/templates';
import type { Study } from '../../src/tree/types';

const HEAD = ['# KIF形式棋譜ファイル Generated by ShogiHome', '手合割：平手', '手数----指手---------消費時間--'];
const mv = (n: number, m: string, branch = false) => `${String(n).padStart(4)} ${m}   ( 0:00/00:00:00)${branch ? '+' : ''}`;

/** 本譜だけ */
const MAIN_ONLY = [...HEAD, mv(1, '７六歩(77)'), mv(2, '３四歩(33)'), mv(3, '２六歩(27)'), mv(4, '８四歩(83)'), ''].join('\n');

/** 3 手目に変化 1 つ */
const ONE_VAR = [
  ...HEAD,
  mv(1, '７六歩(77)'),
  mv(2, '３四歩(33)'),
  mv(3, '２六歩(27)', true),
  mv(4, '８四歩(83)'),
  '',
  '変化：3手',
  mv(3, '６六歩(67)'),
  mv(4, '８四歩(83)'),
  '',
].join('\n');

/** 変化の中の変化（3 手目の変化 ▲6六歩 の 4 手目にさらに変化）とコメント */
const NESTED = [
  ...HEAD,
  '*開始局面のコメント',
  mv(1, '７六歩(77)'),
  '*#評価値=30',
  '*初手は角道',
  mv(2, '３四歩(33)'),
  mv(3, '２六歩(27)', true),
  '*居飛車',
  '*2 行目',
  mv(4, '８四歩(83)'),
  '',
  '変化：3手',
  mv(3, '６六歩(67)'),
  '*#読み筋=△8四歩',
  mv(4, '８四歩(83)', true),
  '*△8四歩なら',
  mv(5, '６八飛(28)'),
  '',
  '変化：4手',
  mv(4, '６二銀(71)'),
  mv(5, '５六歩(57)'),
  '*ここまで',
  '',
].join('\n');

const NO_TEMPLATES: OpeningTemplate[] = [];

async function candidates(text: string, existing: Study[] = [], templates = NO_TEMPLATES) {
  const r = readKif(text);
  if (!r.ok) throw new Error(r.message);
  return buildCandidates(r, templates, existing);
}

describe('KIF の読み取り', () => {
  it('本譜だけ：1 本（初期局面から本譜の終わりまで）', async () => {
    const c = await candidates(MAIN_ONLY);
    expect(c).toHaveLength(1);
    expect(c[0].moves).toEqual(['7g7f', '3c3d', '2g2f', '8c8d']);
    expect(c[0].name).toBe('▲７六歩 △３四歩 ▲２六歩 △８四歩');
    expect(c[0].note).toBe('');
    expect(c[0].branchAt).toBeUndefined();
  });

  it('変化 1 つ：本譜と変化で 2 本。変化は初期局面から変化の終わりまで', async () => {
    const c = await candidates(ONE_VAR);
    expect(c.map((x) => x.moves)).toEqual([
      ['7g7f', '3c3d', '2g2f', '8c8d'],
      ['7g7f', '3c3d', '6g6f', '8c8d'],
    ]);
    expect(c[1].branchAt).toBe(2);
    expect(c[1].name).toBe('▲７六歩 △３四歩 ▲６六歩 △８四歩');
  });

  it('変化の中の変化も 1 本ずつ。名前は長ければ「最初 … 分かれ目（手数付き） … 最後」', async () => {
    const c = await candidates(NESTED);
    expect(c.map((x) => x.moves.join(' '))).toEqual([
      '7g7f 3c3d 2g2f 8c8d',
      '7g7f 3c3d 6g6f 8c8d 2h6h',
      '7g7f 3c3d 6g6f 7a6b 5g5f',
    ]);
    expect(c.map((x) => x.branchAt)).toEqual([undefined, 2, 3]);
    expect(c[1].name).toBe('▲７六歩 … 3手目 ▲６六歩 … ▲６八飛');
    expect(c[2].name).toBe('▲７六歩 … 4手目 △６二銀 … ▲５六歩');
  });

  it('コメント：その終わりまでの手のコメントを手数付きでメモに。「#」で始まる行は入れない。開始局面のコメントも', async () => {
    const c = await candidates(NESTED);
    expect(c[0].note).toBe('開始局面：開始局面のコメント\n1手目 ▲７六歩：初手は角道\n3手目 ▲２六歩：居飛車\n2 行目');
    expect(c[1].note).toBe('開始局面：開始局面のコメント\n1手目 ▲７六歩：初手は角道\n4手目 △８四歩：△8四歩なら');
    expect(c[2].note).toBe('開始局面：開始局面のコメント\n1手目 ▲７六歩：初手は角道\n5手目 ▲５六歩：ここまで');
    expect(cleanComment('#評価値=1\n  #読み筋\n残す\n')).toBe('残す');
  });

  it('同じ手順がすでにあるものには印（初期値は取り込まない）', async () => {
    const existing: Study = { id: 's-x', name: '前からある', note: '', moves: ['7g7f', '3c3d', '6g6f', '8c8d'], mySide: 'white', createdAt: 1, updatedAt: 1 };
    const c = await candidates(ONE_VAR, [existing]);
    expect(c[0].existing).toBeNull();
    expect(c[1].existing?.id).toBe('s-x');
  });

  it('平手以外・読めない・空の KIF は理由を出して取り込まない', () => {
    const kyo = ['手合割：香落ち', '手数----指手---------消費時間--', mv(1, '３四歩(33)'), ''].join('\n');
    expect(readKif(kyo)).toEqual({ ok: false, message: expect.stringContaining('平手の初期局面から始まる棋譜だけ') });
    expect(readKif('')).toEqual({ ok: false, message: '棋譜が空です。' });
    expect(readKif([...HEAD, ''].join('\n'))).toEqual({ ok: false, message: '指し手がありません。' });
    expect(readKif('これは棋譜ではありません\nただの文章')).toMatchObject({ ok: false });
  });

  it('自分の側の初期値は本譜から（戦型が分かればその側、無ければ最後の手を指した側）', () => {
    const r = readKif(MAIN_ONLY);
    if (!r.ok) throw new Error();
    expect(kifSide(r, NO_TEMPLATES)).toBe('white');
    const tpl: OpeningTemplate = { id: 't', name: 't', group: 'g', mySide: 'black', moves: ['7g7f', '3c3d'], note: '', reviewed: true };
    expect(kifSide(r, [tpl])).toBe('black');
  });

  it('メモが 3000 文字を超えたら後ろを切る', async () => {
    const long = [...HEAD, mv(1, '７六歩(77)'), `*${'あ'.repeat(NOTE_MAX + 100)}`, ''].join('\n');
    const c = await candidates(long);
    expect(c[0].note.length).toBe(NOTE_MAX);
    expect(c[0].note.endsWith('（以下略）')).toBe(true);
    expect(c[0].noteCut).toBe(true);
  });
});

describe('このアプリで書き出した KIF を読み戻す', () => {
  it('「★名前」を名前に、その下をメモに。途中の局面で終わる研究手順も戻る', async () => {
    const s = (id: string, name: string, moves: string[], note = ''): Study => ({ id, name, note, moves, mySide: 'white', createdAt: 1, updatedAt: 1 });
    const kif = studiesToKif([
      s('a', '研究A', ['7g7f', '3c3d', '2g2f', '8c8d'], 'Aのメモ'),
      s('b', '研究B', ['7g7f', '3c3d', '6g6f'], 'Bの\nメモ'),
      s('c', '研究C', ['7g7f', '3c3d']),
    ]);
    const c = await candidates(kif);
    expect(c.map((x) => [x.name, x.moves.join(' '), x.note])).toEqual([
      ['研究C', '7g7f 3c3d', ''],
      ['研究A', '7g7f 3c3d 2g2f 8c8d', 'Aのメモ'],
      ['研究B', '7g7f 3c3d 6g6f', 'Bの\nメモ'],
    ]);
  });
});

describe('取り込む研究手順', () => {
  it('選んだ側・戦型・日時（KIF の順に一覧の上から並ぶ）', async () => {
    const tpl: OpeningTemplate = { id: 'tpl', name: 't', group: 'g', mySide: 'black', moves: ['7g7f', '3c3d'], note: '', reviewed: true };
    const c = await candidates(ONE_VAR, [], [tpl]);
    let n = 0;
    const studies = candidatesToStudies(c, 'black', [tpl], 1000, () => `id-${n++}`);
    expect(studies.map((s) => [s.id, s.mySide, s.templateId, s.updatedAt])).toEqual([
      ['id-0', 'black', 'tpl', 1002],
      ['id-1', 'black', 'tpl', 1001],
    ]);
    // 段階10 の直し：自分の側が違う戦型は付けない
    expect(candidatesToStudies(c, 'white', [tpl], 1000).map((s) => s.templateId)).toEqual([undefined, undefined]);
  });

  it('多いとき：少しずつ作り、進み具合を知らせる。上限を超えたら読まない', async () => {
    // 1 手目に 20 通りの変化 → 20 本（▲9六歩〜など、指せる手を並べる）
    const firsts = ['７六歩(77)', '２六歩(27)', '５六歩(57)', '６六歩(67)', '１六歩(17)', '９六歩(97)', '４六歩(47)', '３六歩(37)', '８六歩(87)', '５八玉(59)'];
    const lines = [...HEAD, mv(1, firsts[0], true), ''];
    firsts.slice(1).forEach((m) => lines.push('変化：1手', mv(1, m), ''));
    const r = readKif(lines.join('\n'));
    if (!r.ok) throw new Error(r.message);
    const progress: number[] = [];
    const c = await buildCandidates(r, NO_TEMPLATES, [], (done) => progress.push(done), 3);
    expect(c).toHaveLength(10);
    expect(progress).toEqual([3, 6, 9, 10]);
    expect(KIF_IMPORT_MAX).toBe(2000);
  });
});

describe('ファイルの文字コード', () => {
  it('UTF-8 で読めなければ Shift_JIS', () => {
    const utf8 = new TextEncoder().encode('手合割：平手');
    expect(decodeKifFile(utf8.buffer)).toBe('手合割：平手');
    // 「平手」の Shift_JIS（95BD 8EE8）
    const sjis = new Uint8Array([0x95, 0xbd, 0x8e, 0xe8]);
    expect(decodeKifFile(sjis.buffer)).toBe('平手');
  });
});
